// Package main reads ../../services-config.json and emits Go-literal
// declarations for deployment.Prod, deployment.Test, deployment.ProdConf,
// and deployment.TestConf into ../../data_static_js.go.
//
// Why a generator: the deployment package's runtime init() invokes
// encoding/json on the embedded services-config.json to populate
// those four vars. TinyGo 0.41.1's stdlib doesn't ship the reflect
// runtime helpers (reflect.unsafe_New, reflect.mapassign, etc.)
// that encoding/json needs, so the import was blocking TinyGo
// compilation of the install-page WASM (pkg/skywireconfig/genvisor
// + autoconfigcmd). The split is:
//
//   - config.go               struct defs, var declarations.
//   - config_native.go (!js)  json.Unmarshal-based init for
//     non-WASM builds, with SKYDEPLOY
//     override support.
//   - config_js.go (js)       init that copies from data_static_js.
//   - data_static_js.go (js)  static Go literals, generated here.
//
// Lives under deployment/cmd/gen (not deployment/internal/gen) per
// project convention against `internal/` packages — those break
// out-of-tree test infrastructure that imports skywire from vendor.
//
// Run via `go generate ./deployment/` or directly:
//
//	cd deployment/cmd/gen && go run .
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"strings"
)

type servicesEnv struct {
	Test json.RawMessage `json:"test"`
	Prod json.RawMessage `json:"prod"`
}

type services struct {
	Conf               string   `json:"conf,omitempty"`
	ConfDmsg           string   `json:"conf_dmsg,omitempty"`
	DmsgDiscovery      string   `json:"dmsg_discovery,omitempty"`
	TransportDiscovery string   `json:"transport_discovery,omitempty"`
	AddressResolver    string   `json:"address_resolver,omitempty"`
	RouteFinder        string   `json:"route_finder,omitempty"`
	RouteSetupNodes    []string `json:"route_setup_nodes,omitempty"`
	TransportSetupPKs  []string `json:"transport_setup,omitempty"`
	UptimeTracker      string   `json:"uptime_tracker,omitempty"`
	ServiceDiscovery   string   `json:"service_discovery,omitempty"`
	StunServers        []string `json:"stun_servers,omitempty"`
	DNSServer          string   `json:"dns_server,omitempty"`
	GeoIP              string   `json:"geoip,omitempty"`
	SurveyWhitelist    []string `json:"survey_whitelist,omitempty"`
	DmsgServers        []struct {
		Static string `json:"static"`
		Server struct {
			Address string `json:"address"`
		} `json:"server"`
	} `json:"dmsg_servers,omitempty"`
	DmsgDiscoveryDmsg      string `json:"dmsg_discovery_dmsg,omitempty"`
	TransportDiscoveryDmsg string `json:"transport_discovery_dmsg,omitempty"`
	AddressResolverDmsg    string `json:"address_resolver_dmsg,omitempty"`
	RouteFinderDmsg        string `json:"route_finder_dmsg,omitempty"`
	UptimeTrackerDmsg      string `json:"uptime_tracker_dmsg,omitempty"`
	ServiceDiscoveryDmsg   string `json:"service_discovery_dmsg,omitempty"`
	RewardSystem           string `json:"reward_system,omitempty"`
	RewardSystemDmsg       string `json:"reward_system_dmsg,omitempty"`
}

func main() {
	wd, err := os.Getwd()
	if err != nil {
		log.Fatal(err)
	}
	// Resolve paths relative to the generator's own location so the
	// generator works whether invoked via `go generate` (cwd =
	// deployment/) or `go run .` from this dir.
	jsonPath := filepath.Join(wd, "../../services-config.json")
	outPath := filepath.Join(wd, "../../data_static_js.go")

	raw, err := os.ReadFile(jsonPath) //nolint:gosec // generator reads a known repo-relative input
	if err != nil {
		log.Fatalf("read %s: %v", jsonPath, err)
	}

	var env servicesEnv
	if err := json.Unmarshal(raw, &env); err != nil {
		log.Fatalf("unmarshal env: %v", err)
	}
	var prod, test services
	if err := json.Unmarshal(env.Prod, &prod); err != nil {
		log.Fatalf("unmarshal prod: %v", err)
	}
	if err := json.Unmarshal(env.Test, &test); err != nil {
		log.Fatalf("unmarshal test: %v", err)
	}

	var buf bytes.Buffer
	buf.WriteString(`// Code generated by deployment/cmd/gen; DO NOT EDIT.

//go:build js

// Package deployment pkg/deployment/data_static_js.go
//
// Static-data variant of the prod / test deployment bundles. The
// non-WASM build path (config_native.go) populates deployment.Prod
// / Test by unmarshalling the embedded services-config.json at
// init time; that drags encoding/json and the reflect runtime
// helpers TinyGo can't link. Under js/wasm we use these literals
// instead — config_js.go's init copies them into the public vars.
//
// Regenerate after editing services-config.json:
//   go generate ./deployment/
package deployment

import (
	"github.com/skycoin/skywire/pkg/cipher"
)

`)
	buf.WriteString("var prodData = Services{\n")
	emitServices(&buf, prod)
	buf.WriteString("}\n\n")

	buf.WriteString("var testData = Services{\n")
	emitServices(&buf, test)
	buf.WriteString("}\n\n")

	buf.WriteString(fmt.Sprintf("var prodConfData = Conf{Conf: %q}\n", prod.Conf))
	buf.WriteString(fmt.Sprintf("var testConfData = Conf{Conf: %q}\n", test.Conf))

	out, err := format.Source(buf.Bytes())
	if err != nil {
		// Write unformatted on format error so the developer can see
		// what the generator produced and fix the template.
		_ = os.WriteFile(outPath, buf.Bytes(), 0o600) //nolint:errcheck
		log.Fatalf("gofmt: %v\nunformatted output written to %s", err, outPath)
	}
	if err := os.WriteFile(outPath, out, 0o600); err != nil {
		log.Fatalf("write %s: %v", outPath, err)
	}
	fmt.Printf("wrote %s (%d bytes)\n", outPath, len(out))
}

func emitServices(buf *bytes.Buffer, s services) {
	emitStringField(buf, "DmsgDiscovery", s.DmsgDiscovery)
	emitStringField(buf, "TransportDiscovery", s.TransportDiscovery)
	emitStringField(buf, "AddressResolver", s.AddressResolver)
	emitStringField(buf, "RouteFinder", s.RouteFinder)
	emitPubKeyList(buf, "RouteSetupNodes", s.RouteSetupNodes)
	emitPubKeyList(buf, "TransportSetupPKs", s.TransportSetupPKs)
	emitStringField(buf, "UptimeTracker", s.UptimeTracker)
	emitStringField(buf, "ServiceDiscovery", s.ServiceDiscovery)
	emitStringList(buf, "StunServers", s.StunServers)
	emitStringField(buf, "DNSServer", s.DNSServer)
	emitStringField(buf, "GeoIP", s.GeoIP)
	emitPubKeyList(buf, "SurveyWhitelist", s.SurveyWhitelist)
	emitStringField(buf, "ConfDmsg", s.ConfDmsg)
	emitDmsgServers(buf, s.DmsgServers)
	emitStringField(buf, "DmsgDiscoveryDmsg", s.DmsgDiscoveryDmsg)
	emitStringField(buf, "TransportDiscoveryDmsg", s.TransportDiscoveryDmsg)
	emitStringField(buf, "AddressResolverDmsg", s.AddressResolverDmsg)
	emitStringField(buf, "RouteFinderDmsg", s.RouteFinderDmsg)
	emitStringField(buf, "UptimeTrackerDmsg", s.UptimeTrackerDmsg)
	emitStringField(buf, "ServiceDiscoveryDmsg", s.ServiceDiscoveryDmsg)
	emitStringField(buf, "RewardSystem", s.RewardSystem)
	emitStringField(buf, "RewardSystemDmsg", s.RewardSystemDmsg)
}

func emitStringField(buf *bytes.Buffer, name, val string) {
	if val == "" {
		return
	}
	fmt.Fprintf(buf, "\t%s: %q,\n", name, val)
}

func emitStringList(buf *bytes.Buffer, name string, vals []string) {
	if len(vals) == 0 {
		return
	}
	fmt.Fprintf(buf, "\t%s: []string{\n", name)
	for _, v := range vals {
		fmt.Fprintf(buf, "\t\t%q,\n", v)
	}
	buf.WriteString("\t},\n")
}

func emitPubKeyList(buf *bytes.Buffer, name string, vals []string) {
	if len(vals) == 0 {
		return
	}
	fmt.Fprintf(buf, "\t%s: []cipher.PubKey{\n", name)
	for _, v := range vals {
		fmt.Fprintf(buf, "\t\tmustPubKey(%q),\n", v)
	}
	buf.WriteString("\t},\n")
}

func emitDmsgServers(buf *bytes.Buffer, entries []struct {
	Static string `json:"static"`
	Server struct {
		Address string `json:"address"`
	} `json:"server"`
}) {
	if len(entries) == 0 {
		return
	}
	buf.WriteString("\tDmsgServers: []DmsgServerEntry{\n")
	for _, e := range entries {
		var sb strings.Builder
		sb.WriteString("\t\t{")
		fmt.Fprintf(&sb, "Static: %q, ", e.Static)
		fmt.Fprintf(&sb, "Server: struct {\n\t\t\tAddress string `json:\"address\"`\n\t\t}{Address: %q}", e.Server.Address)
		sb.WriteString("},\n")
		buf.WriteString(sb.String())
	}
	buf.WriteString("\t},\n")
}
